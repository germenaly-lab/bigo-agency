export const AVAILABLE_ICON_NAMES = Object.keys(ICON_REGISTRY);

export function resolveIcon(iconInput, fallback = Sparkles) {
  if (!iconInput) return fallback;
  if (typeof iconInput === 'function' || typeof iconInput === 'object') {
    return iconInput;
  }
  if (typeof iconInput === 'string') {
    const matched = ICON_REGISTRY[iconInput];
    if (matched) return matched;
  }
  return fallback;
}
